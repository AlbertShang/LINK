"""Convert a pure PEMS district dataset to the STAGANN dataset format.

The pure-dataset layout is shared by PEMS03/04/07/08::

    pure_dataset_topk/pems0{district}/district_{district}_flow.npy
    pure_dataset_topk/pems0{district}/district_{district}_adj_inout_topkK.npy
    pure_dataset_topk/pems0{district}/adj_index.pkl

By default this script keeps the pure dataset's fixed node split and configured
directed in/out Top-K adjacency, uses STAGANN's
7:3 temporal split (validation and test share the last 30%), and writes the
``data.pkl``, ``scaler.pkl``, ``index.pkl`` and ``adj_mx.pkl`` files expected by
``STKrigingDataset``. It intentionally uses the graph artifact generated by the
new pure-dataset pipeline rather than regenerating an ASTGNN adjacency.
"""

from __future__ import annotations

import argparse
import json
import pickle
from pathlib import Path
from typing import Any

import numpy as np


STAGANN_DIR = Path(__file__).resolve().parents[2]
REPOSITORY_ROOT = STAGANN_DIR.parents[1]
PURE_DATASET_ROOT = REPOSITORY_ROOT / "pure_dataset_topk"
SUPPORTED_DISTRICTS = (3, 4, 7, 8)
TYPE_CATEGORIES = ("mainline", "onramp", "offramp", "hov", "other")
DIRECTION_CATEGORIES = ("n", "s", "e", "w", "ne", "nw", "se", "sw", "other")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a STAGANN dataset from a pure PEMS district dataset."
    )
    parser.add_argument("--district", type=int, choices=SUPPORTED_DISTRICTS, default=3)
    parser.add_argument(
        "--top-k",
        type=int,
        default=None,
        help=(
            "Select district_<id>_adj_inout_topkK.npy explicitly. When omitted, "
            "read top_k from preprocess_config.json for backward compatibility."
        ),
    )
    parser.add_argument("--seq-len", type=int, default=24)
    parser.add_argument("--steps-per-day", type=int, default=288)
    parser.add_argument(
        "--start-weekday",
        type=int,
        default=6,
        help="Weekday index (Monday=0) of the first sample; PEMS03 starts on Sunday (6).",
    )
    parser.add_argument("--train-series-ratio", type=float, default=0.7)
    parser.add_argument("--valid-test-split", action="store_true",
                        help="Split the post-training time windows into validation and test sets.")
    parser.add_argument("--valid-series-ratio", type=float, default=0.1)
    parser.add_argument("--target-channel", type=int, default=0)
    parser.add_argument(
        "--missing-value-strategy",
        choices=("temporal-interpolate", "error"),
        default="temporal-interpolate",
        help="How to handle NaN/Inf in pure flow before STAGANN normalization.",
    )
    parser.add_argument("--tod", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--dow", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument(
        "--pure-dir",
        type=Path,
        default=None,
        help="Override the pure dataset directory (useful for PEMS04/07/08).",
    )
    parser.add_argument(
        "--metadata-file",
        type=Path,
        default=None,
        help="Override district_<id>_node_metadata.npz from the pure dataset directory.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Override the STAGANN output directory.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow replacing STAGANN artifacts in an existing output directory.",
    )
    return parser.parse_args()


def pure_paths(
    district: int,
    pure_dir: Path | None,
    top_k_override: int | None,
) -> tuple[Path, Path, Path, Path]:
    if pure_dir is not None:
        root = pure_dir
    else:
        root = PURE_DATASET_ROOT / f"pems{district:02d}"
    if top_k_override is not None:
        top_k = top_k_override
    else:
        config_path = root / "preprocess_config.json"
        if not config_path.is_file():
            raise FileNotFoundError(
                f"Missing new pure-dataset configuration: {config_path}"
            )
        with config_path.open("r", encoding="utf-8") as file:
            preprocessing_config = json.load(file)
        top_k = int(preprocessing_config.get("top_k", 0))
    if top_k <= 0:
        raise ValueError(f"top_k must be positive, got {top_k}")
    adjacency_path = root / f"district_{district}_adj_inout_topk{top_k}.npy"
    return (
        root,
        root / f"district_{district}_flow.npy",
        adjacency_path,
        root / "adj_index.pkl",
    )


def validate_ratios(args: argparse.Namespace) -> None:
    if args.seq_len <= 0 or args.steps_per_day <= 0:
        raise ValueError("--seq-len and --steps-per-day must be positive.")
    if not 0 < args.train_series_ratio < 1:
        raise ValueError("--train-series-ratio must be between 0 and 1.")
    if args.valid_test_split and not 0 < args.valid_series_ratio < 1:
        raise ValueError("--valid-series-ratio must be between 0 and 1.")
    if not 0 <= args.start_weekday <= 6:
        raise ValueError("--start-weekday must be in [0, 6] (Monday=0).")


def load_flow(flow_path: Path, target_channel: int) -> np.ndarray:
    flow = np.load(flow_path)
    if flow.ndim == 2:
        flow = flow[..., np.newaxis]
    if flow.ndim != 3:
        raise ValueError(f"Flow must have shape [time, node, channel], got {flow.shape}.")
    if not 0 <= target_channel < flow.shape[-1]:
        raise ValueError(
            f"target channel {target_channel} is invalid for flow with {flow.shape[-1]} channels."
        )
    flow = flow[..., target_channel:target_channel + 1].astype(np.float32, copy=False)
    return flow


def fill_missing_temporally(flow: np.ndarray, strategy: str) -> tuple[np.ndarray, int]:
    """Fill each node/channel independently along time.

    STAGANN normalizes the entire input before its dataset class can replace
    NaNs.  Therefore missing values must be handled before fitting the scaler.
    Linear interpolation is consistent with the pure-dataset training helpers;
    leading/trailing gaps use the closest observed value.
    """
    invalid = ~np.isfinite(flow)
    missing_count = int(invalid.sum())
    if missing_count == 0:
        return flow, missing_count
    if strategy == "error":
        raise ValueError("Flow contains NaN or Inf; select temporal interpolation to continue.")

    filled = flow.copy()
    time = np.arange(flow.shape[0])
    for node in range(flow.shape[1]):
        for channel in range(flow.shape[2]):
            values = filled[:, node, channel]
            valid = np.isfinite(values)
            if not valid.any():
                raise ValueError(f"Node {node}, channel {channel} has no finite observations.")
            if not valid.all():
                values[~valid] = np.interp(time[~valid], time[valid], values[valid])
    return filled, missing_count


def load_adjacency(adjacency_path: Path, node_count: int) -> np.ndarray:
    adjacency = np.load(adjacency_path).astype(np.float32, copy=False)
    if adjacency.shape != (node_count, node_count):
        raise ValueError(
            f"Adjacency has shape {adjacency.shape}; expected ({node_count}, {node_count})."
        )
    if not np.isfinite(adjacency).all():
        raise ValueError(f"Adjacency contains NaN or Inf: {adjacency_path}")
    return adjacency


def load_node_split(split_path: Path, node_count: int) -> dict[str, Any]:
    with split_path.open("rb") as file:
        split = pickle.load(file)

    required = ("train_nodes", "valid_nodes", "test_nodes")
    if not isinstance(split, dict) or any(key not in split for key in required):
        raise ValueError(f"{split_path} must contain {required}.")

    nodes = []
    for key in required:
        values = np.asarray(split[key], dtype=np.int64)
        if values.ndim != 1:
            raise ValueError(f"{key} must be one-dimensional, got {values.shape}.")
        if np.any(values < 0) or np.any(values >= node_count):
            raise ValueError(f"{key} contains an out-of-range node index.")
        split[key] = values
        nodes.append(values)

    all_nodes = np.concatenate(nodes)
    if len(all_nodes) != node_count or np.unique(all_nodes).size != node_count:
        raise ValueError("The pure node split must be a non-overlapping partition of all nodes.")
    return split


def make_time_split(
    time_steps: int,
    seq_len: int,
    train_series_ratio: float,
    valid_test_split: bool,
    valid_series_ratio: float,
) -> dict[str, list[tuple[int, int]]]:
    window_count = time_steps - seq_len + 1
    if window_count <= 0:
        raise ValueError(f"seq_len={seq_len} is longer than the time dimension {time_steps}.")

    windows = [(start, start + seq_len) for start in range(window_count)]
    train_count = round(window_count * train_series_ratio)
    if not 0 < train_count < window_count:
        raise ValueError("Temporal train split leaves no validation/test samples.")

    if valid_test_split:
        valid_count = round(window_count * valid_series_ratio)
        if train_count + valid_count >= window_count:
            raise ValueError("Temporal train/validation split leaves no test samples.")
        valid = windows[train_count:train_count + valid_count]
        test = windows[train_count + valid_count:]
    else:
        # This is the behavior used by STAGANN's existing PEMS03 preparation code.
        valid = windows[train_count:]
        test = valid

    return {"train": windows[:train_count], "valid": valid, "test": test}


def standard_normalize(flow: np.ndarray, train_index: list[tuple[int, int]]) -> tuple[np.ndarray, dict[str, Any]]:
    # Match STAGANN's standard_transform: include the final temporal point of
    # the last training window when computing the scaler.
    training_end = train_index[-1][1]
    training_flow = flow[:training_end, ..., 0]
    mean = training_flow.mean()
    std = training_flow.std()
    if not np.isfinite(std) or std == 0:
        raise ValueError("Training flow has zero or invalid standard deviation.")

    scaler = {
        "func": "re_standard_transform",
        "args": {"mean": mean, "std": std},
    }
    return (flow - mean) / std, scaler


def add_calendar_features(
    normalized_flow: np.ndarray,
    steps_per_day: int,
    start_weekday: int,
    add_tod: bool,
    add_dow: bool,
) -> np.ndarray:
    time_steps, node_count, _ = normalized_flow.shape
    features = [normalized_flow]

    if add_tod:
        tod = (np.arange(time_steps, dtype=np.float32) % steps_per_day) / steps_per_day
        features.append(np.broadcast_to(tod[:, None, None], (time_steps, node_count, 1)))
    if add_dow:
        dow = ((np.arange(time_steps) // steps_per_day + start_weekday) % 7).astype(np.float32)
        features.append(np.broadcast_to(dow[:, None, None], (time_steps, node_count, 1)))

    return np.concatenate(features, axis=-1).astype(np.float32, copy=False)


def prepare_output_dir(output_dir: Path, overwrite: bool) -> None:
    artifact_names = {"data.pkl", "scaler.pkl", "index.pkl", "adj_index.pkl", "adj_mx.pkl", "metadata.pkl", "dataset_info.json"}
    if output_dir.exists() and not overwrite:
        existing = artifact_names.intersection(path.name for path in output_dir.iterdir())
        if existing:
            raise FileExistsError(
                f"{output_dir} already contains STAGANN artifacts {sorted(existing)}. "
                "Use --overwrite to replace them."
            )
    output_dir.mkdir(parents=True, exist_ok=True)


def write_artifacts(
    output_dir: Path,
    processed_data: np.ndarray,
    adjacency: np.ndarray,
    node_split: dict[str, Any],
    time_split: dict[str, list[tuple[int, int]]],
    scaler: dict[str, Any],
    metadata: dict[str, Any],
    info: dict[str, Any],
) -> None:
    with (output_dir / "data.pkl").open("wb") as file:
        pickle.dump({"processed_data": processed_data}, file, protocol=pickle.HIGHEST_PROTOCOL)
    with (output_dir / "scaler.pkl").open("wb") as file:
        pickle.dump(scaler, file, protocol=pickle.HIGHEST_PROTOCOL)
    with (output_dir / "index.pkl").open("wb") as file:
        pickle.dump(time_split, file, protocol=pickle.HIGHEST_PROTOCOL)
    with (output_dir / "adj_index.pkl").open("wb") as file:
        pickle.dump(node_split, file, protocol=pickle.HIGHEST_PROTOCOL)
    with (output_dir / "adj_mx.pkl").open("wb") as file:
        pickle.dump(adjacency, file, protocol=pickle.HIGHEST_PROTOCOL)
    with (output_dir / "metadata.pkl").open("wb") as file:
        pickle.dump(metadata, file, protocol=pickle.HIGHEST_PROTOCOL)
    with (output_dir / "dataset_info.json").open("w", encoding="utf-8") as file:
        json.dump(info, file, ensure_ascii=False, indent=2)


def normalize_freeway(value: str | None) -> str:
    if value is None or not str(value).strip():
        return ""
    try:
        numeric = float(value)
        if numeric.is_integer():
            return str(int(numeric))
    except (TypeError, ValueError):
        pass
    return str(value).strip().lower()


def build_metadata_features(
    metadata_path: Path,
    node_count: int,
    train_nodes: np.ndarray,
) -> dict[str, Any]:
    """Encode the canonical ``src.metadata.NodeMetadata`` artifact.

    Type and direction features are copied exactly from the new pure dataset.
    The canonical freeway strings are converted to a train-node-only one-hot
    vocabulary because neural baselines require numeric inputs.  Validation or
    test freeways absent from training use one explicit unknown bucket.
    """
    required = {
        "type_code", "direction_code", "type_feature", "direction_feature",
        "freeway", "type_categories", "direction_categories",
    }
    with np.load(metadata_path, allow_pickle=False) as archive:
        missing = required.difference(archive.files)
        if missing:
            raise KeyError(f"Node metadata is missing {sorted(missing)}: {metadata_path}")
        type_code = archive["type_code"].astype(np.int64, copy=False)
        direction_code = archive["direction_code"].astype(np.int64, copy=False)
        type_feature = archive["type_feature"].astype(np.float32, copy=False)
        direction_feature = archive["direction_feature"].astype(np.float32, copy=False)
        freeway_values = [normalize_freeway(value) for value in archive["freeway"]]
        type_categories = tuple(str(value) for value in archive["type_categories"])
        direction_categories = tuple(
            str(value) for value in archive["direction_categories"]
        )

    if type_categories != TYPE_CATEGORIES:
        raise ValueError(
            f"Unexpected type vocabulary {type_categories}; expected {TYPE_CATEGORIES}"
        )
    if direction_categories != DIRECTION_CATEGORIES:
        raise ValueError(
            "Unexpected direction vocabulary "
            f"{direction_categories}; expected {DIRECTION_CATEGORIES}"
        )
    if (
        type_code.shape != (node_count,)
        or direction_code.shape != (node_count,)
        or type_feature.shape != (node_count, len(TYPE_CATEGORIES))
        or direction_feature.shape != (node_count, len(DIRECTION_CATEGORIES))
        or len(freeway_values) != node_count
    ):
        raise ValueError(
            "Canonical node metadata is not aligned with the flow node axis: "
            f"type={type_feature.shape}, direction={direction_feature.shape}, "
            f"freeway={len(freeway_values)}, nodes={node_count}"
        )
    if not np.array_equal(type_feature.argmax(axis=1), type_code):
        raise ValueError("type_code and type_feature disagree in canonical metadata")
    if not np.array_equal(direction_feature.argmax(axis=1), direction_code):
        raise ValueError(
            "direction_code and direction_feature disagree in canonical metadata"
        )
    if not (
        np.allclose(type_feature.sum(axis=1), 1.0)
        and np.allclose(direction_feature.sum(axis=1), 1.0)
    ):
        raise ValueError("Canonical Type/Direction metadata must be one-hot")

    train_freeways = sorted({freeway_values[index] for index in train_nodes if freeway_values[index]})
    freeway_categories = tuple(train_freeways) + ("__unknown__",)
    freeway_to_index = {value: index for index, value in enumerate(freeway_categories)}
    freeway_feature = np.zeros((node_count, len(freeway_categories)), dtype=np.float32)
    unknown_freeway_index = len(freeway_categories) - 1
    for row, freeway in enumerate(freeway_values):
        freeway_feature[row, freeway_to_index.get(freeway, unknown_freeway_index)] = 1.0

    node_features = np.concatenate(
        [type_feature, direction_feature, freeway_feature], axis=1
    ).astype(np.float32, copy=False)
    if not np.isfinite(node_features).all():
        raise ValueError("Encoded metadata contains NaN or Inf.")

    type_end = type_feature.shape[1]
    direction_end = type_end + direction_feature.shape[1]
    freeway_end = direction_end + freeway_feature.shape[1]
    return {
        "node_features": node_features,
        "type_code": type_code,
        "direction_code": direction_code,
        "freeway": np.asarray(freeway_values),
        "config": {
            "layout_version": "canonical-node-metadata-v2",
            "node_feature_dim": int(node_features.shape[1]),
            "type_slice": [0, type_end],
            "direction_slice": [type_end, direction_end],
            "freeway_slice": [direction_end, freeway_end],
            "direction_other_index": type_end + DIRECTION_CATEGORIES.index("other"),
            "freeway_unknown_index": direction_end + unknown_freeway_index,
            "type_categories": list(TYPE_CATEGORIES),
            "direction_categories": list(DIRECTION_CATEGORIES),
            "freeway_categories_train_only": list(train_freeways),
            "source_artifact": metadata_path.name,
            "source_features": ["type_feature", "direction_feature", "freeway"],
        },
    }


def main() -> None:
    args = parse_args()
    validate_ratios(args)
    pure_dir, flow_path, adjacency_path, split_path = pure_paths(
        args.district, args.pure_dir, args.top_k
    )
    adjacency_top_k = int(adjacency_path.stem.rsplit("topk", 1)[1])
    output_dir = (
        args.output_dir
        or STAGANN_DIR
        / "datasets"
        / f"pems{args.district:02d}_metadata_topk{adjacency_top_k}_71_24"
    )
    output_dir = output_dir.resolve()
    metadata_path = (
        args.metadata_file
        or pure_dir / f"district_{args.district}_node_metadata.npz"
    )

    for path in (flow_path, adjacency_path, split_path, metadata_path):
        if not path.is_file():
            raise FileNotFoundError(
                f"Missing pure PEMS{args.district:02d} input: {path}. "
                "Create the same pure-dataset artifacts before adapting this district."
            )

    flow = load_flow(flow_path, args.target_channel)
    flow, missing_count = fill_missing_temporally(flow, args.missing_value_strategy)
    adjacency = load_adjacency(adjacency_path, flow.shape[1])
    node_split = load_node_split(split_path, flow.shape[1])
    metadata = build_metadata_features(metadata_path, flow.shape[1], node_split["train_nodes"])
    time_split = make_time_split(
        flow.shape[0], args.seq_len, args.train_series_ratio,
        args.valid_test_split, args.valid_series_ratio,
    )
    normalized_flow, scaler = standard_normalize(flow, time_split["train"])
    processed_data = add_calendar_features(
        normalized_flow, args.steps_per_day, args.start_weekday, args.tod, args.dow
    )

    prepare_output_dir(output_dir, args.overwrite)
    info = {
        "district": args.district,
        "source_dir": str(pure_dir.resolve()),
        "flow_file": flow_path.name,
        "adjacency_file": adjacency_path.name,
        "adjacency_top_k": adjacency_top_k,
        "node_split_file": split_path.name,
        "metadata_file": metadata_path.name,
        "processed_data_shape": list(processed_data.shape),
        "adjacency_shape": list(adjacency.shape),
        "node_split_sizes": {key: int(len(node_split[key])) for key in ("train_nodes", "valid_nodes", "test_nodes")},
        "time_split_sizes": {key: int(len(value)) for key, value in time_split.items()},
        "sequence_length": args.seq_len,
        "steps_per_day": args.steps_per_day,
        "start_weekday": args.start_weekday,
        "train_series_ratio": args.train_series_ratio,
        "valid_test_split": args.valid_test_split,
        "calendar_features": {"time_of_day": args.tod, "day_of_week": args.dow},
        "metadata": metadata["config"],
        "missing_values": {
            "source_non_finite_count": missing_count,
            "strategy": args.missing_value_strategy,
        },
        "adjacency": (
            "Configured directed in/out Top-K graph copied from the pure dataset "
            "without symmetrization or binarization."
        ),
    }
    write_artifacts(output_dir, processed_data, adjacency, node_split, time_split, scaler, metadata, info)

    print(f"Generated STAGANN dataset: {output_dir}")
    print(f"processed_data: {processed_data.shape} ({processed_data.dtype})")
    print(f"adjacency:      {adjacency.shape}, nonzero={np.count_nonzero(adjacency)}")
    print(f"missing values: {missing_count} ({args.missing_value_strategy})")
    print(f"metadata:       {metadata['node_features'].shape} (Type/Direction/Fwy)")
    print("node split:     " + ", ".join(f"{key}={len(node_split[key])}" for key in ("train_nodes", "valid_nodes", "test_nodes")))
    print("time split:     " + ", ".join(f"{key}={len(value)}" for key, value in time_split.items()))


if __name__ == "__main__":
    main()
